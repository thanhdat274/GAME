/** Nội thất nhìn chính diện; kích thước khớp footprint (1 ô = 16 điểm ảnh). */
function makeFridgeSprite(width: number, height: number, single: boolean): Sprite {
  const pixels = Array.from({ length: height }, () => Array(width).fill('.')) as string[][];
  const rect = (x: number, y: number, w: number, h: number, fill: string, border?: string) => {
    for (let py = y; py < y + h; py++) for (let px = x; px < x + w; px++) {
      pixels[py][px] = border && (px === x || px === x + w - 1 || py === y || py === y + h - 1) ? border : fill;
    }
  };
  if (single) {
    rect(4, 0, 8, 2, 'L', 'k');
    rect(2, 2, 12, 13, 'L', 'k');
    rect(3, 3, 10, 9, 'i', 'S');
    rect(11, 6, 1, 4, 's');
    rect(3, 12, 10, 2, 'S', 'k');
    rect(4, 15, 3, 1, 'g');
    rect(9, 15, 3, 1, 'g');
  } else {
    rect(6, 0, 20, 3, 'L', 'k');
    rect(2, 2, 28, 12, 'L', 'k');
    rect(3, 4, 12, 8, 'i', 'S');
    rect(17, 4, 12, 8, 'i', 'S');
    rect(15, 3, 2, 10, 'S', 'k');
    rect(14, 7, 1, 3, 's');
    rect(17, 7, 1, 3, 's');
    rect(4, 6, 10, 1, 'W');
    rect(18, 6, 10, 1, 'W');
    rect(4, 9, 10, 1, 'W');
    rect(18, 9, 10, 1, 'W');
    rect(2, 14, 28, 1, 'g', 'k');
    rect(5, 15, 4, 1, 'S');
    rect(23, 15, 4, 1, 'S');
  }
  return pixels.map((row) => row.join(''));
}

